create table stock_movement (
    id           bigint generated by default as identity primary key,
    warehouse_id bigint       not null references warehouse,
    product_id   bigint       not null references product,
    quantity     integer      not null check (quantity <> 0),
    type         varchar(20)  not null check (type in ('RECEIPT', 'SALE', 'ADJUSTMENT')),
    occurred_at  timestamp    not null,
    note         varchar(200),
    check (
        (type = 'RECEIPT' and quantity > 0)
        or (type = 'SALE' and quantity < 0)
        or type = 'ADJUSTMENT'
    )
);

create index stock_movement_item_idx on stock_movement (warehouse_id, product_id, occurred_at);

create function reject_stock_movement_change() returns trigger language plpgsql as $$
begin
    raise exception 'stock_movement is append-only, record an ADJUSTMENT instead'
        using errcode = 'restrict_violation';
end;
$$;

create trigger stock_movement_no_update_or_delete
    before update or delete on stock_movement
    for each row execute function reject_stock_movement_change();

create trigger stock_movement_no_truncate
    before truncate on stock_movement
    for each statement execute function reject_stock_movement_change();
