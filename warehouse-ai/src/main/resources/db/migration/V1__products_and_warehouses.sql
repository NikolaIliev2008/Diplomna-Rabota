-- Master data: where goods are kept, what is sold and who supplies it.
-- Stock is deliberately not stored here: it will come from the stock ledger (next migration).

create table warehouse (
    id   bigint generated by default as identity primary key,
    code varchar(20)  not null unique,
    name varchar(100) not null
);

create table supplier (
    id             bigint generated by default as identity primary key,
    name           varchar(100) not null unique,
    lead_time_days integer      not null check (lead_time_days > 0)
);

create table product (
    id            bigint generated by default as identity primary key,
    sku           varchar(30)   not null unique,
    name          varchar(150)  not null,
    category      varchar(60)   not null,
    brand         varchar(60)   not null,
    package_size  varchar(30)   not null,
    price_eur     numeric(10,2) not null check (price_eur > 0),
    reorder_point integer       not null check (reorder_point >= 0)
);

-- Many-to-many: a product can have several suppliers, each with its own cost
create table supplier_product (
    supplier_id bigint        not null references supplier,
    product_id  bigint        not null references product,
    cost_eur    numeric(10,2) not null check (cost_eur > 0),
    primary key (supplier_id, product_id)
);

-- Finds the suppliers of one product without scanning the whole table
create index supplier_product_product_idx on supplier_product (product_id);
